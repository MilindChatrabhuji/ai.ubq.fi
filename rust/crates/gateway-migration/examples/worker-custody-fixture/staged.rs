//! Fixed synthetic >32MiB producer through the same real common-DO port.
use super::{host, inputs, port, producers, support_run};
use gateway_core::{
    js_string::JsString16,
    source_graph::{GraphAtom, SourceGraph},
    state::AuthorityStore,
    tuple_key::TupleKey,
};
use gateway_migration::{staged::*, *};
use serde::{Deserialize, Serialize};
use std::{fs::OpenOptions, os::unix::fs::OpenOptionsExt, path::Path};
#[derive(Deserialize)]
struct Prepared {
    directory: String,
    capture: NativeCapture,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Resume {
    v: u32,
    operation: String,
    artifacts: operational::ArtifactInput,
}
fn file(path: &Path) -> Result<std::fs::File, MigrationError> {
    OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(path)
        .map_err(|_| port::error("Private staged fixture file failed").into())
}
fn encode<T: Serialize>(file: &mut std::fs::File, value: &T) -> Result<(), MigrationError> {
    serde_json::to_writer(&mut *file, value)
        .map_err(|_| port::error("Private staged fixture serialization failed"))?;
    file.sync_all().map_err(port::error)?;
    Ok(())
}
// Fixed metadata-only markers let the existing external sampler attribute RSS.
fn mark(directory: &str, stage: &str) -> Result<(), MigrationError> {
    let epoch_ms = u64::try_from(
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_err(port::error)?
            .as_millis(),
    )
    .map_err(port::error)?;
    encode(
        &mut file(&Path::new(directory).join(format!("rss-{stage}.json")))?,
        &serde_json::json!({"stage":stage,"pid":std::process::id(),"epoch_ms":epoch_ms}),
    )
}
pub fn run(directory: &str, now_ms: i64, prepare_only: bool) -> Result<(), MigrationError> {
    let prepared: Prepared = serde_json::from_str(
        &serde_json::to_string(&inputs::prepare(directory, now_ms)?).map_err(port::error)?,
    )
    .map_err(port::error)?;
    mark(directory, "fixture_construction")?;
    let mut source = prepared.capture;
    let time = inputs::FixtureTime::new(now_ms)?;
    //160 quarter-MiB scalar payloads; exact graph transport is generated by the
    // real codec. All source rows/indexes/custody are audited TOGETHER, once.
    for index in 0..160 {
        source.entries.push(NativeEntry {
            raw_key: TupleKey::from_parts(&[
                gateway_core::tuple_key::KeyPart::String("default".into()),
                gateway_core::tuple_key::KeyPart::String(format!("staged-history-{index:03}")),
            ])?
            .sort_bytes()
            .to_vec(),
            value: NativeValue::SourceGraphV1(graph_transport::to_source_graph(&SourceGraph {
                root: GraphAtom::String(JsString16::from_utf8(&"x".repeat(256 * 1024))),
                nodes: vec![],
            })?),
            revision: source.data_revision.clone(),
            expiration_ms: -1,
        });
    }
    let source_path = Path::new(directory).join("large-source.json");
    encode(&mut file(&source_path)?, &source)?;
    let source_bytes = std::fs::metadata(&source_path).map_err(port::error)?.len();
    if source_bytes <= operational::PRIVATE_WIRE_MAX_BYTES as u64 {
        return Err(port::error("Synthetic full capture did not exceed32MiB").into());
    }
    mark(directory, "native_audit_stage_plan")?;
    let fixed = host::Host::from_stopped_fixture(&prepared.directory, &source, time.runtime())?;
    let source_rows = source.entries.len();
    drop(source);
    let source_inventory = native_stage::Captured::read(
        &source_path,
        &native_stage::directory(Path::new(directory))?,
    )?;
    let mut plan = support_run(
        native_stage::Captured::read(
            &source_path,
            &native_stage::directory(Path::new(directory))?,
        )?
        .prepare(&fixed),
    )?;
    mark(directory, "staged_begin_append")?;
    if prepare_only {
        let mut frames = 0;
        let mut maximum = 0;
        let mut frame = Vec::new();
        while plan.write_next_batch(&mut frame)? {
            maximum = maximum.max(frame.len());
            frames += 1;
            frame.clear();
        }
        mark(directory, "prepared_only_complete")?;
        return port::write(&serde_json::json!({"operation":"staged_prepared_only","source_bytes":source_bytes,"source_rows":source_rows,"bounded_frames":frames,"max_stage_frame_bytes":maximum,"target_touched":false})).map_err(Into::into);
    }
    let store = port::Store::default();
    support_run(execute_staged(&store, plan.begin()))?;
    let first = plan
        .next_batch()?
        .ok_or_else(|| port::error("No staged batch"))?;
    let mut wire_max = serde_json::to_vec(&first).map_err(port::error)?.len();
    // Actual DO unchanged by invalid append, then one complete batch is written.
    if let StageRequest::Append(mut corrupt) =
        decode_stage_request(&serde_json::to_vec(&first).map_err(port::error)?)?
    {
        corrupt.sequence += 1;
        if support_run(execute_staged(&store, StageRequest::Append(corrupt))).is_ok() {
            return Err(port::error("Reordered staged batch accepted").into());
        }
    }
    support_run(execute_staged(&store, first))?;
    if support_run(execute_staged(&store, plan.seal())).is_ok()
        || support_run(export_native_latest(&store, time.export())).is_ok()
    {
        return Err(port::error("Partial staged target became accepted").into());
    }
    port::write(
        &serde_json::json!({"operation":"staged_partial","source_bytes":source_bytes,"source_rows":source_rows,"unsealed_refused":true}),
    )?;
    let resume: Resume = port::read()?;
    if resume.v != 1 || resume.operation != "staged_resume" {
        return Err(port::error("Expected staged restart/resume phase").into());
    }
    mark(directory, "staged_resume")?;
    while let Some(batch) = plan.next_batch()? {
        wire_max = wire_max.max(serde_json::to_vec(&batch).map_err(port::error)?.len());
        if let StageRequest::Append(mut corrupt) =
            decode_stage_request(&serde_json::to_vec(&batch).map_err(port::error)?)?
        {
            corrupt.digest = "0".repeat(64);
            if support_run(execute_staged(&store, StageRequest::Append(corrupt))).is_ok() {
                return Err(port::error("Corrupt staged digest accepted").into());
            }
        }
        let duplicate = decode_stage_request(&serde_json::to_vec(&batch).map_err(port::error)?)?;
        support_run(execute_staged(&store, batch))?;
        if support_run(execute_staged(&store, duplicate)).is_ok() {
            return Err(port::error("Duplicate staged batch accepted").into());
        }
    }
    mark(directory, "staged_seal_runtime")?;
    let sealed = support_run(execute_staged(&store, plan.seal()))?;
    if !sealed.sealed || sealed.activation_authorized {
        return Err(port::error("Staged seal receipt differs").into());
    }
    let runtime = producers::exercise(&store, time)?;
    let current =
        support_run(store.read(&gateway_auth::provider_credentials::codex_source_pool_key()))?
            .ok_or_else(|| port::error("Missing actual source pool"))?;
    let fixed = fixed.with_current_pool(&current, time.export())?;
    mark(directory, "latest_inverse")?;
    let latest_path = Path::new(directory).join("large-latest.json");
    let controls_path = Path::new(directory).join("large-custody.json");
    let rows = support_run(native_operator::write_private_latest(
        &store,
        time.export(),
        &fixed,
        resume.artifacts.into(),
        &mut file(&latest_path)?,
        &mut file(&controls_path)?,
    ))?;
    mark(directory, "inverse_verification")?;
    let latest = native_stage::Captured::read(
        &latest_path,
        &native_stage::directory(Path::new(directory))?,
    )?;
    let mut keys = std::collections::BTreeMap::new();
    let mut ordinal = 0;
    latest.visit_entries(&mut |entry| {
        if keys.insert(entry.raw_key.clone(), ordinal).is_some() {
            return Err(port::error("Duplicate latest raw key"));
        }
        ordinal += 1;
        Ok(())
    })?;
    source_inventory.visit_entries(&mut |entry| {
        if entry
            .raw_key
            .windows(b"staged-history-".len())
            .any(|w| w == b"staged-history-")
        {
            let index = keys
                .get(&entry.raw_key)
                .ok_or_else(|| port::error("Large historical row missing from latest inverse"))?;
            if serde_json::to_vec(entry).map_err(port::error)?
                != serde_json::to_vec(&latest.entry(*index)?).map_err(port::error)?
            {
                return Err(port::error(
                    "Large historical metadata/value changed in inverse",
                ));
            }
        }
        Ok(())
    })?;
    mark(directory, "finished")?;
    port::write(
        &serde_json::json!({"operation":"staged_exercised","source_bytes":source_bytes,"latest_bytes":std::fs::metadata(latest_path).map_err(port::error)?.len(),"source_rows":source_rows,"latest_rows":rows,"max_stage_frame_bytes":wire_max,"receipt":sealed,"runtime":runtime,"source_file":source_path.to_str(),"latest_file":Path::new(directory).join("large-latest.json").to_str(),"custody_file":controls_path.to_str(),"historical_roundtrip_exact":true,"cases":["complete_native_audit_before_staging","over32mib_bounded_common_do_transfer","reordered_corrupt_duplicate_batches_refused","partial_seal_and_inverse_refused","partial_common_do_restart_resumed","staged_seal_not_atomic_adoption_or_activation","actual_post_restart_auth_admission_latest_write_delete","native_private_latest_sink_exact_large_history"]}),
    )?;
    Ok(())
}

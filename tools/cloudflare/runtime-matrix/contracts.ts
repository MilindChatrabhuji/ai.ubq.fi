import assert from "node:assert/strict";
import { normalizeSelectedProviderIds } from "../../../src/provider/selection.ts";
import { captureUnexpectedStatus, registerFixtureResponse } from "./failure-capture.ts";

export type MatrixScenario = "direct" | "codex" | "claude" | "paid";
export type MatrixProvider = "codex" | "claude" | "surplus" | "openlux" | "lithos" | "openrouter" | "deepseek";
export type MatrixContext = {
  url(path: string): string;
  post(path: string, body: unknown, token?: string, signal?: AbortSignal): Promise<Response>;
  rpc(body: unknown): Promise<Record<string, unknown>>;
  read(key: string): Promise<Record<string, unknown> | null>;
  lifecycle(id: string): Promise<Record<string, unknown>>;
  events(): Promise<unknown[]>;
  cases: string[];
  /** Generated by the real isolated setup; never printed or included in receipts. */
  clientToken?: string;
  adminToken?: string;
};
export type MatrixHarness = MatrixContext & {
  /** A fresh namespace/disk and source-compatible Rust setup, never a proof-row reset. */
  withScenario(kind: MatrixScenario, run: (context: MatrixContext) => Promise<void>): Promise<void>;
};

export function object(value: unknown): Record<string, unknown> {
  assert(value !== null && typeof value === "object" && !Array.isArray(value), "Expected a complete object response");
  return value as Record<string, unknown>;
}

export async function responseObject(response: Response, status = 200): Promise<Record<string, unknown>> {
  await captureUnexpectedStatus(response, status);
  assert.equal(response.status, status, "Unexpected matrix response status; raw credential-bearing bodies are not logged");
  return object(await response.json());
}

export async function selectProviders(context: MatrixContext, providerIds: string[]): Promise<void> {
  const result = await responseObject(await context.post("/admin/providers/selection", { provider_ids: providerIds }, context.adminToken ?? "fixture-admin"));
  assert.equal(result.stored, true);
  assert.deepEqual(result.provider_ids, normalizeSelectedProviderIds(providerIds));
}

export async function post(context: MatrixContext, path: string, body: unknown, signal?: AbortSignal): Promise<Response> {
  return registerFixtureResponse(await context.post(path, body, context.clientToken ?? "fixture-access", signal), body);
}

export async function createClient(context: MatrixContext, paid = false): Promise<{ token: string; id: string }> {
  const result = await responseObject(
    await context.post(
      "/admin/api-keys",
      { name: "controlled runtime matrix", paid_fallback_enabled: paid, ...(paid ? { paid_fallback_limit_credits: 100 } : {}) },
      context.adminToken ?? "fixture-admin"
    )
  );
  assert(typeof result.token === "string" && typeof result.id === "string", "The actual admin route must create the isolated principal");
  return { token: result.token, id: result.id };
}

/** Read-only spelling of the source tuple codec's string components. */
export function stringKey(...parts: string[]): string {
  return "tuple-v1:" + parts.map((part) => "02" + Buffer.from(part).toString("hex").replaceAll("00", "00ff") + "00").join("");
}

export function dispatches(events: unknown[], marker: string): Record<string, unknown>[] {
  return events
    .filter((value) => value !== null && typeof value === "object" && !Array.isArray(value))
    .map((value) => object(value))
    .filter((value) => value.kind === "matrix_dispatch" && value.marker === marker);
}

export async function settled(context: MatrixContext, response: Response): Promise<Record<string, unknown>> {
  const id = response.headers.get("x-uos-request-id");
  assert(id, "Actual Rust correlation is required");
  const state = await context.lifecycle(id);
  const terminal = object(state.terminal_intent);
  assert.notEqual(terminal.delivery, "delivered", "Worker EOF cannot manufacture native delivery");
  return state;
}

export function assertSingleAdmission(state: Record<string, unknown>, provider: string): void {
  assert(Array.isArray(state.attempts) && state.attempts.length === 1, "One actual attempt must retain one original admission");
  const attempt = object(state.attempts[0]);
  assert.equal(attempt.transport_started, true);
  assert.equal(attempt.provider, provider);
}
